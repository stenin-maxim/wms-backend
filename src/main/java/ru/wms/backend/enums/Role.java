package ru.wms.backend.enums;

public enum Role {
    SUPER_ADMIN, // Разработчик платформы — доступ ко всем компаниям, биллингу и тарифам SaaS
    ADMIN,       // Владелец бизнеса / Директор конкретной компании (полный доступ к своему складу)
    MANAGER,     // Заведующий складом / Старший менеджер (управление ячейками, номенклатурой)
    STOREKEEPER, // Кладовщик-приемщик (принимает товар от поставщиков, проверяет брак, оформляет излишки)
    PICKER,      // Комплектовщик / Сборщик заказов (работает строго с ТСД на сборку по листу заказа)
    AUDITOR      // Ревизор / Бухгалтер по учету (имеет доступ только к инвентаризации и просмотру остатков)
}
